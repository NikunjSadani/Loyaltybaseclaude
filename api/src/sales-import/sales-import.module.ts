import { Module, type OnModuleInit } from '@nestjs/common';
import { PrismaModule } from '../prisma/prisma.module';
import { SalesImportIngestModule } from './ingest/sales-import-ingest.module';
import { SalesImportKpiModule } from './kpi/sales-import-kpi.module';
import { SalesImportConfigController } from './sales-import-config.controller';
import { SalesImportApplyController } from './sales-import-apply.controller';
import { SalesImportController } from './sales-import.controller';
import { SalesMonthsController } from './sales-months.controller';
import { SalesImportDrainController } from './sales-import-drain.controller';
import { SalesImportRunnerService } from './ingest/sales-import-runner.service';
import { SalesApplyJobsService } from './apply/sales-apply-jobs.service';

/**
 * Sales Import: DMS invoice-line file → importer-owned monthly KPI achievements.
 * See platform/docs/plans/SALES-IMPORT-PIPELINE-PLAN.md. Dormant unless the tenant's
 * `features.salesImport === true` (every route 403s otherwise, via assertSalesImportAccess).
 *
 * OWNER: Lane-0. The lanes do NOT edit this file: Lane I registers providers in
 * ingest/sales-import-ingest.module.ts, Lane K in kpi/sales-import-kpi.module.ts, and each lane adds
 * handlers only to its own controller files.
 *
 * CONTROLLER ORDER IS LOAD-BEARING: Express matches routes in registration order, so the controllers
 * with STATIC segments under `admin/sales-import` (`profile`, `kpis`, `kpis/test`) are registered BEFORE
 * SalesImportController's `GET admin/sales-import/:id`. Pinned by sales-import.module.spec.ts.
 */
@Module({
  imports: [PrismaModule, SalesImportIngestModule, SalesImportKpiModule],
  controllers: [
    SalesImportConfigController,
    SalesImportApplyController,
    SalesImportController,
    SalesMonthsController,
    SalesImportDrainController,
  ],
})
export class SalesImportModule implements OnModuleInit {
  constructor(
    private readonly runner: SalesImportRunnerService,
    private readonly jobs: SalesApplyJobsService,
  ) {}

  /** Inline runner (local / e2e): the same loop also runs the background Apply / Recalculate jobs (2026-11-18). */
  onModuleInit(): void {
    this.runner.registerDrain(() => this.jobs.drain());
  }
}
