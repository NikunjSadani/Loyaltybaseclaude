/**
 * Credits & Payouts — Upload Parser
 *
 * Parses an Excel file uploaded by the client admin, validates each row,
 * and returns a CreditParseResult.
 *
 * Validation rules per outlet+field cell:
 *  1. Outlet ID must exist in eligible outlets
 *  2. Outlet must be active
 *  3. Zero or blank value → SKIP (not an error)
 *  4. Negative value → ERROR ("Amount cannot be negative") — UNLESS the tenant setting
 *     `creditUploadNegativeDeductions` is ON (opt `negativeDeductions`), then:
 *       - POINTS (known outlet): a DEDUCTION row, status OK, amount = −(magnitude rounded
 *         half-up to a whole point): −199.5 → −200, −199.4 → −199. A magnitude that rounds to 0
 *         (−0.4) → SKIP (nothing to deduct). The rounded magnitude counts against the points cap.
 *       - PAYOUT: ERROR "Payout amounts can't be negative — deduct via Reversals."
 *       - unknown outlet: only the "not found" error.
 *     Deductions are summed separately (summary.deducted / totalDeductedPoints); totalPoints
 *     stays the CREDITED (positive) total.
 *  5. Any number of decimals is accepted, then ROUNDED HALF-UP to a whole unit (owner rule
 *     2026-11-12: points AND ₹ payouts are credited in whole units — 199.5 → 200, 199.4 → 199).
 *     A positive value that rounds to 0 → SKIP (nothing to credit).
 *  6. ROUNDED amount (deductions: rounded magnitude) exceeds safety cap → ERROR
 *  7. Duplicate outlet+field in the same upload → ERROR on second occurrence
 *  8. Field configured as NA for this outlet type → SKIP
 *
 * Expected sheet format (generated by generateCreditTemplate):
 *   Row 0: title (skipped)
 *   Row 1: headers  — Outlet ID | Outlet Name | Field1 | ... | FieldN | Field1 Narration | ...
 *   Row 2+: data
 */

import * as XLSX from 'xlsx';
import type { CreditField, CreditParseResult, CreditUploadRow } from '@/types';
import type { TemplateOutlet } from './credits-payouts-template';
import { rupeesToPaise } from './money';

export interface ParseCreditUploadOpts {
  fields:      CreditField[];
  outlets:     TemplateOutlet[];
  month:       string;         // 'YYYY-MM'
  safetyCapPoints: number;
  /** Safety cap in rupees (displayed to user). Internally compared after converting input to rupees. */
  safetyCapInr:    number;
  /**
   * Tenant setting `creditUploadNegativeDeductions`. When true a negative POINTS value is a
   * deduction row instead of an error. Default false (byte-identical to the pre-feature parser).
   */
  negativeDeductions?: boolean;
}

const EMPTY_SUMMARY: CreditParseResult['summary'] = {
  total: 0, ok: 0, skipped: 0, errors: 0, totalPoints: 0, totalPayoutPaise: 0, rounded: 0,
  deducted: 0, totalDeductedPoints: 0,
};

// ─── Whole-unit rounding ──────────────────────────────────────────────────────

/**
 * Round a non-negative amount HALF-UP to a whole unit (199.5 → 200, 199.4 → 199).
 * Math.round is half-up for the non-negative values that reach here (negatives are
 * rejected first). The backend independently rejects any non-whole amount.
 */
export function roundHalfUpWhole(n: number): number {
  return Math.round(trimFloatNoise(n));
}

/**
 * Strip binary floating-point noise from a typed/computed amount before rounding or display.
 * Excel formula cells arrive as raw doubles (=116*12.5/100 → 14.499999999999998), which would
 * otherwise round DOWN and show as "14.499999999999998" in the preview/report. Trimming to 12
 * significant digits restores 14.5 (→ rounds half-up to 15).
 *
 * Only finite, non-negative, non-integer values below 1e11 are touched (12 significant digits
 * then still keep every integer digit plus ≥1 decimal); NaN, ±Infinity, negatives (rejected
 * upstream with the value as typed), integers and huge values are returned unchanged.
 */
export function trimFloatNoise(n: number): number {
  if (!Number.isFinite(n) || n < 0 || Number.isInteger(n) || n >= 1e11) return n;
  return Number(n.toPrecision(12));
}

// ─── Parser ───────────────────────────────────────────────────────────────────

export function parseCreditUpload(
  buffer:  ArrayBuffer,
  opts:    ParseCreditUploadOpts,
): CreditParseResult {
  const { fields, outlets, safetyCapPoints, safetyCapInr } = opts;
  const negativeDeductions = opts.negativeDeductions === true;

  // Build outlet lookup
  const outletMap = new Map<string, TemplateOutlet>();
  for (const o of outlets) outletMap.set(o.id, o);

  // Active fields only, in order
  const activeFields = fields.filter((f) => f.isActive);

  // Parse workbook
  let wb: XLSX.WorkBook;
  try {
    wb = XLSX.read(buffer, { type: 'array' });
  } catch {
    return {
      headerError: 'Could not read the uploaded file. Please upload a valid .xlsx file.',
      rows:        [],
      hasErrors:   false,
      canProceed:  false,
      summary:     { ...EMPTY_SUMMARY },
    };
  }

  const sheetName = wb.SheetNames[0];
  if (!sheetName) {
    return {
      headerError: 'The uploaded file has no sheets.',
      rows:        [],
      hasErrors:   false,
      canProceed:  false,
      summary:     { ...EMPTY_SUMMARY },
    };
  }

  const ws = wb.Sheets[sheetName];

  // Read all rows as arrays (row 0 = title, row 1 = headers, row 2+ = data)
  const allRows = XLSX.utils.sheet_to_json<(string | number)[]>(ws, {
    header: 1,
    defval: '',
  }) as (string | number)[][];

  if (allRows.length < 2) {
    return {
      headerError: 'The file has no header row.',
      rows:        [],
      hasErrors:   false,
      canProceed:  false,
      summary:     { ...EMPTY_SUMMARY },
    };
  }

  // Row index 1 is the header row (row index 0 is title)
  const headerRow = allRows[1].map((h) => String(h).trim());
  const outletIdIdx   = headerRow.indexOf('Outlet ID');
  const outletNameIdx = headerRow.indexOf('Outlet Name');

  if (outletIdIdx === -1) {
    return {
      headerError: 'Missing "Outlet ID" column. Please use the official template.',
      rows:        [],
      hasErrors:   false,
      canProceed:  false,
      summary:     { ...EMPTY_SUMMARY },
    };
  }

  // Map field name → column index for both values and narrations
  const fieldValueIdx     = new Map<string, number>();
  const fieldNarrationIdx = new Map<string, number>();
  for (const f of activeFields) {
    const vi = headerRow.indexOf(f.name);
    const ni = headerRow.indexOf(`${f.name} Narration`);
    if (vi !== -1) fieldValueIdx.set(f.id, vi);
    if (ni !== -1) fieldNarrationIdx.set(f.id, ni);
  }

  // Track duplicates: "outletId|fieldId"
  const seen = new Set<string>();

  const rows: CreditUploadRow[] = [];
  let totalPoints      = 0;
  let totalPayoutPaise = 0;
  let deductedCount       = 0;
  let totalDeductedPoints = 0;

  // Data rows start at index 2
  for (let rIdx = 2; rIdx < allRows.length; rIdx++) {
    const row = allRows[rIdx];
    const outletId   = String(row[outletIdIdx] ?? '').trim();
    const outletName = outletNameIdx !== -1 ? String(row[outletNameIdx] ?? '').trim() : '';

    if (!outletId) continue;  // blank row

    const outlet = outletMap.get(outletId);

    // Process each active field as a separate result row
    for (const field of activeFields) {
      const vi = fieldValueIdx.get(field.id);
      if (vi === undefined) continue;  // column not in file

      const rawVal   = row[vi] ?? '';
      const rawNarr  = fieldNarrationIdx.has(field.id)
        ? String(row[fieldNarrationIdx.get(field.id)!] ?? '').trim()
        : '';

      const strVal = String(rawVal).trim();

      // SKIP: blank or zero (check before outlet validation so blanks don't generate errors)
      if (strVal === '' || strVal === '0') {
        rows.push({
          rowNum:    rIdx + 1,
          outletId,
          outletName: outletName || (outlet?.name ?? outletId),
          fieldId:   field.id,
          fieldName: field.name,
          amount:    0,
          narration: rawNarr,
          awardType: 'POINTS',
          status:    'SKIP',
          errors:    [],
          skipReason: 'Value is blank or zero — nothing to credit for this row.',
        });
        continue;
      }

      const errors: string[] = [];

      // Unknown outlet — must be validated before NA check
      if (!outlet) {
        errors.push(`Outlet ID "${outletId}" not found in the active outlet master.`);
      }

      // Determine award type for this outlet type (only when outlet is known)
      const awardType: 'POINTS' | 'PAYOUT' | 'NA' =
        outlet ? (field.outletTypeAwards[outlet.type] ?? 'NA') : 'POINTS';

      // SKIP: NA field for this outlet type (only when outlet is known and no other error)
      if (outlet && awardType === 'NA') {
        rows.push({
          rowNum:    rIdx + 1,
          outletId,
          outletName: outlet.name,
          fieldId:   field.id,
          fieldName: field.name,
          amount:    0,
          narration: rawNarr,
          awardType: 'POINTS',
          status:    'SKIP',
          errors:    [],
          skipReason: `Field "${field.name}" is set to Not Applicable (NA) for outlet type "${outlet.typeLabel ?? outlet.type}". Configure its award type in Field Configuration to credit this outlet.`,
        });
        continue;
      }

      // Parse numeric value
      // Float noise trimmed up-front so the rounded amount, originalAmount ("Typed Amount" in
      // the report / preview panel) and every message all use the clean value (14.5, not
      // 14.499999999999998 from an Excel formula cell).
      const numVal = trimFloatNoise(Number(strVal.replace(/,/g, '')));

      // Deduction (setting ON, negative value): typed value float-trimmed on its magnitude
      // (trimFloatNoise only handles non-negatives), magnitude rounded half-up to whole points.
      let deduction: { typed: number; magnitude: number } | null = null;

      if (isNaN(numVal)) {
        errors.push(`Value "${strVal}" is not a valid number.`);
      } else if (negativeDeductions && numVal < 0) {
        if (!outlet) {
          // Unknown outlet: the "not found" error above is the only error.
        } else if (awardType === 'PAYOUT') {
          errors.push(`Payout amounts can't be negative — deduct via Reversals.`);
        } else {
          const typed     = -trimFloatNoise(Math.abs(numVal));
          const magnitude = roundHalfUpWhole(Math.abs(numVal));
          if (magnitude > safetyCapPoints) {
            const shown = magnitude !== -typed ? `${typed} (rounds to -${magnitude})` : `${typed}`;
            errors.push(`Deduction ${shown} exceeds the safety cap of ${safetyCapPoints} for points.`);
          }
          deduction = { typed, magnitude };
        }
      } else {
        // Negative
        if (numVal < 0) {
          errors.push(`Amount cannot be negative (got ${numVal}).`);
        }
        // Safety cap — applied to the ROUNDED whole amount (what is actually credited).
        const cap = awardType === 'POINTS' ? safetyCapPoints : safetyCapInr;
        const roundedForCap = roundHalfUpWhole(numVal);
        if (roundedForCap > cap) {
          const shown = roundedForCap !== numVal ? `${numVal} (rounds to ${roundedForCap})` : `${numVal}`;
          errors.push(`Amount ${shown} exceeds the safety cap of ${cap} for ${awardType === 'POINTS' ? 'points' : '₹'}.`);
        }
      }

      // A deduction whose magnitude rounds to 0 (e.g. −0.4) deducts nothing → SKIP, not an error.
      if (deduction && errors.length === 0 && deduction.magnitude === 0) {
        rows.push({
          rowNum:    rIdx + 1,
          outletId,
          outletName: outletName || (outlet?.name ?? outletId),
          fieldId:   field.id,
          fieldName: field.name,
          amount:    0,
          originalAmount: deduction.typed,
          narration: rawNarr,
          awardType: 'POINTS',
          status:    'SKIP',
          errors:    [],
          skipReason: `Value ${deduction.typed} rounds to 0 — amounts are deducted in whole units, so nothing is deducted for this row.`,
        });
        continue;
      }

      // A positive amount that rounds to 0 (e.g. 0.4) credits nothing → SKIP, not an error.
      if (!deduction && errors.length === 0 && !isNaN(numVal) && roundHalfUpWhole(numVal) === 0) {
        rows.push({
          rowNum:    rIdx + 1,
          outletId,
          outletName: outletName || (outlet?.name ?? outletId),
          fieldId:   field.id,
          fieldName: field.name,
          amount:    0,
          originalAmount: numVal,
          narration: rawNarr,
          awardType: awardType === 'PAYOUT' ? 'PAYOUT' : 'POINTS',
          status:    'SKIP',
          errors:    [],
          skipReason: `Value ${numVal} rounds to 0 — amounts are credited in whole units, so nothing is credited for this row.`,
        });
        continue;
      }

      // Duplicate check
      const dedupKey = `${outletId}|${field.id}`;
      if (seen.has(dedupKey)) {
        errors.push(`Duplicate entry: Outlet "${outletId}" + Field "${field.name}" appears more than once in this upload.`);
      } else if (errors.length === 0) {
        seen.add(dedupKey);
      }

      // Whole units only: points and rupees are both rounded half-up before crediting.
      // Deductions: amount = −(rounded magnitude); "rounded" compares against the typed value.
      const amount = isNaN(numVal) ? 0
        : deduction ? -deduction.magnitude
        : roundHalfUpWhole(numVal);
      const typedVal = deduction ? deduction.typed : numVal;
      const wasRounded = !isNaN(numVal) && amount !== typedVal;
      const status: 'OK' | 'ERROR' = errors.length > 0 ? 'ERROR' : 'OK';
      // awardType at this point is always POINTS or PAYOUT (NA was handled above)
      const resolvedAwardType: 'POINTS' | 'PAYOUT' = awardType === 'PAYOUT' ? 'PAYOUT' : 'POINTS';

      if (status === 'OK') {
        if (deduction) {
          deductedCount       += 1;
          totalDeductedPoints += deduction.magnitude;
        } else if (resolvedAwardType === 'POINTS') {
          totalPoints += amount;
        } else {
          // PAYOUT rows: the user entered rupees (now rounded to whole rupees); convert to
          // integer paise for the payload — always a multiple of 100.
          totalPayoutPaise += rupeesToPaise(amount);
        }
      }

      // For PAYOUT rows the amount stored in CreditUploadRow.amount is paise;
      // for POINTS rows it remains whole points (no ×100 conversion).
      const storedAmount = resolvedAwardType === 'PAYOUT' ? rupeesToPaise(amount) : amount;

      rows.push({
        rowNum:    rIdx + 1,
        outletId,
        outletName: outletName || (outlet?.name ?? outletId),
        fieldId:   field.id,
        fieldName: field.name,
        amount:    storedAmount,
        // Only present when rounding changed the value (as typed: points or RUPEES), so a
        // whole-number upload's payload is byte-identical to before.
        ...(wasRounded ? { originalAmount: typedVal } : {}),
        narration: rawNarr,
        awardType: resolvedAwardType,
        status,
        errors,
      });
    }
  }

  const okCount      = rows.filter((r) => r.status === 'OK').length;
  const skippedCount = rows.filter((r) => r.status === 'SKIP').length;
  const errorCount   = rows.filter((r) => r.status === 'ERROR').length;
  const roundedCount = rows.filter((r) => r.status === 'OK' && r.originalAmount !== undefined).length;
  const hasErrors    = errorCount > 0;

  return {
    headerError:   null,
    rows,
    hasErrors,
    canProceed:    !hasErrors && okCount > 0,
    summary: {
      total:          okCount + errorCount,
      ok:             okCount,
      skipped:        skippedCount,
      errors:         errorCount,
      totalPoints,
      totalPayoutPaise,
      rounded:        roundedCount,
      deducted:       deductedCount,
      totalDeductedPoints,
    },
  };
}
